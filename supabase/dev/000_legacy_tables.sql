-- Creates empty copies of the live site's two tables so the backup CSVs
-- can be imported, then setup_v2.sql copies them into the new tables.
-- Structure matches the live project (checked 2026-09-24).
-- =====================================================================
begin;

create table public.kitecab (
  id         bigint primary key,
  created_at timestamptz not null default now(),
  key        text not null,
  value      jsonb
);

create table public.payments (
  id                       bigint generated by default as identity primary key,
  created_at               timestamptz default now(),
  updated_at               timestamptz default now(),
  booking_id               bigint,
  customer_name            text,
  mobile                   text,
  booking_amount           numeric,
  advance_amount           numeric,
  payment_type             text,
  status                   text,
  payment_link             text,
  razorpay_payment_link_id text,
  razorpay_payment_id      text,
  reference_id             text,
  paid_at                  timestamp without time zone,
  webhook_response         jsonb
);

-- Backup copies only: nobody but the service key may read them.
alter table public.kitecab  enable row level security;
alter table public.payments enable row level security;
revoke all on public.kitecab, public.payments from anon, authenticated;

commit;
