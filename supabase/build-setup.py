"""
Builds supabase/setup_v2.sql from supabase/migrations/*.sql (in order).

    python supabase/build-setup.py

Edit the migration files, never setup_v2.sql. The data summary from 003 is moved to
the very end so the Supabase SQL editor shows it as the result.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = """-- =====================================================================
-- KiteCab v2 — ONE-TIME SETUP (paste everything into the Supabase SQL Editor, click Run)
--
-- Run it on the NEW development project, after dev/000_legacy_tables.sql and the
-- CSV import (see README). It only reads the copied `kitecab` / `payments` tables.
-- Each part runs in a transaction; undo with rollback_v2.sql.
--
-- Generated by supabase/build-setup.py from supabase/migrations — edit those, not this file.
-- =====================================================================

"""


def main():
    parts, summary = [], ''
    for f in sorted((HERE / 'migrations').glob('*.sql')):
        sql = f.read_text(encoding='utf-8')
        if '-- ---------- report' in sql:
            sql, summary = sql.split('-- ---------- report', 1)
            summary = '-- ---------- summary (this is what the SQL Editor shows)' + summary
        parts.append(f'-- ##################### {f.name} #####################\n{sql.strip()}\n')
    out = HERE / 'setup_v2.sql'
    out.write_text(HEADER + '\n'.join(parts) + '\n' + summary.strip() + '\n', encoding='utf-8', newline='\n')
    print(f'{out.name}: {len(parts)} migrations')


if __name__ == '__main__':
    main()
